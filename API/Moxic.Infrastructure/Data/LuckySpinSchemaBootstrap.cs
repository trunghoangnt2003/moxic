using Microsoft.EntityFrameworkCore;

namespace Moxic.Infrastructure.Data;

/// <summary>
/// Idempotent DDL for the lucky-spin + contact-settings tables.
/// Program.cs uses EnsureCreated (a no-op on existing databases), so existing
/// dev/test/prod databases receive these tables here. DDL copied from
/// `dotnet ef dbcontext script` (migration AddLuckySpinAndContactSettings).
/// NOTE: no curly braces in the SQL — ExecuteSqlRaw treats them as format placeholders.
/// </summary>
public static class LuckySpinSchemaBootstrap
{
    private const string Ddl = """
        CREATE TABLE IF NOT EXISTS "ContactSettings" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY,
            "MessengerUrl" character varying(500),
            "Zalo" character varying(500),
            "PhoneNumber" character varying(30),
            "UpdatedAt" timestamp with time zone NOT NULL,
            CONSTRAINT "PK_ContactSettings" PRIMARY KEY ("Id")
        );

        CREATE TABLE IF NOT EXISTS "SpinCodes" (
            "Id" uuid NOT NULL,
            "Code" character varying(32) NOT NULL,
            "MaxUses" integer NOT NULL,
            "UsedCount" integer NOT NULL,
            "ExpiresAt" timestamp with time zone,
            "IsActive" boolean NOT NULL,
            "Note" character varying(200),
            "CreatedAt" timestamp with time zone NOT NULL,
            CONSTRAINT "PK_SpinCodes" PRIMARY KEY ("Id")
        );

        CREATE TABLE IF NOT EXISTS "SpinPrizes" (
            "Id" uuid NOT NULL,
            "Name" character varying(100) NOT NULL,
            "Type" character varying(20) NOT NULL,
            "GameId" uuid,
            "Probability" numeric(5,2) NOT NULL,
            "IsActive" boolean NOT NULL,
            "DisplayOrder" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL,
            "UpdatedAt" timestamp with time zone NOT NULL,
            CONSTRAINT "PK_SpinPrizes" PRIMARY KEY ("Id"),
            CONSTRAINT "FK_SpinPrizes_Games_GameId" FOREIGN KEY ("GameId") REFERENCES "Games" ("Id") ON DELETE SET NULL
        );

        CREATE TABLE IF NOT EXISTS "SpinHistories" (
            "Id" uuid NOT NULL,
            "SpinCodeId" uuid,
            "CodeText" character varying(32) NOT NULL,
            "PrizeId" uuid,
            "PrizeName" character varying(100) NOT NULL,
            "PrizeType" character varying(20) NOT NULL,
            "GameId" uuid,
            "RewardCode" character varying(32),
            "IsClaimed" boolean NOT NULL,
            "ClaimedAt" timestamp with time zone,
            "ClientIp" character varying(64),
            "CreatedAt" timestamp with time zone NOT NULL,
            CONSTRAINT "PK_SpinHistories" PRIMARY KEY ("Id"),
            CONSTRAINT "FK_SpinHistories_SpinCodes_SpinCodeId" FOREIGN KEY ("SpinCodeId") REFERENCES "SpinCodes" ("Id") ON DELETE SET NULL,
            CONSTRAINT "FK_SpinHistories_SpinPrizes_PrizeId" FOREIGN KEY ("PrizeId") REFERENCES "SpinPrizes" ("Id") ON DELETE SET NULL
        );

        CREATE UNIQUE INDEX IF NOT EXISTS "IX_SpinCodes_Code" ON "SpinCodes" ("Code");
        CREATE INDEX IF NOT EXISTS "IX_SpinHistories_CreatedAt" ON "SpinHistories" ("CreatedAt");
        CREATE INDEX IF NOT EXISTS "IX_SpinHistories_PrizeId" ON "SpinHistories" ("PrizeId");
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_SpinHistories_RewardCode" ON "SpinHistories" ("RewardCode");
        CREATE INDEX IF NOT EXISTS "IX_SpinHistories_SpinCodeId" ON "SpinHistories" ("SpinCodeId");
        CREATE INDEX IF NOT EXISTS "IX_SpinPrizes_GameId" ON "SpinPrizes" ("GameId");
        """;

    public static async Task EnsureAsync(MoxicDbContext db)
    {
        await db.Database.ExecuteSqlRawAsync(Ddl);
    }
}
